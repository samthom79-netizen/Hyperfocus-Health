/**
 * Prints the WCAG AA contrast table for every colour pairing in
 * src/config/palette.ts and writes it to docs/contrast-report.md.
 *
 * Run: node scripts/check-contrast.ts
 * Exits with an error if any pairing that should pass fails.
 */
import { writeFileSync } from 'node:fs';
import { AA, contrastRatio } from '../src/lib/contrast.ts';
import { colourOf, pairings } from '../src/config/palette.ts';

const useLabel = { text: 'Normal text (4.5:1)', largeText: 'Large text (3:1)', nonText: 'Icons/borders (3:1)' };

let failures = 0;
const rows = pairings.map((p) => {
  const fg = colourOf(p.fg);
  const bg = colourOf(p.bg);
  const ratio = contrastRatio(fg, bg);
  const passes = ratio >= AA[p.use];
  const ok = p.expectFail ? !passes : passes;
  if (!ok) failures++;
  const result = passes ? 'Pass' : p.expectFail ? 'Fail (expected: never use)' : 'FAIL';
  return `| ${p.fg} ${fg} | ${p.bg} ${bg} | ${ratio.toFixed(2)}:1 | ${useLabel[p.use]} | ${result} | ${p.where} |`;
});

const table = [
  '| Foreground | Background | Ratio | Needed for | Result | Used for |',
  '| --- | --- | --- | --- | --- | --- |',
  ...rows,
].join('\n');

const report = `# Colour contrast report (WCAG 2.2 AA)

Generated by \`node scripts/check-contrast.ts\` from \`src/config/palette.ts\`.

${table}
`;

writeFileSync(new URL('../docs/contrast-report.md', import.meta.url), report);
console.log(table);
console.log(failures ? `\n${failures} pairing(s) failed.` : '\nAll pairings behave as expected.');
process.exit(failures ? 1 : 0);
